  ON public.user_access_profiles (profile_key)
  WHERE profile_key = 'root';

CREATE TABLE IF NOT EXISTS public.user_branch_access (
  user_id uuid NOT NULL REFERENCES public.user_access_profiles (user_id)
    ON DELETE CASCADE,
  schema_name text NOT NULL REFERENCES public.empresas_esquemas (schema_name)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, schema_name)
);

CREATE TABLE IF NOT EXISTS public.profile_table_permissions (
  profile_key text NOT NULL REFERENCES public.access_profiles (profile_key)
    ON UPDATE RESTRICT ON DELETE RESTRICT,
  schema_name text NOT NULL REFERENCES public.empresas_esquemas (schema_name)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  table_name text NOT NULL,
  can_select boolean NOT NULL DEFAULT false,
  can_insert boolean NOT NULL DEFAULT false,
  can_update boolean NOT NULL DEFAULT false,
  can_delete boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (profile_key, schema_name, table_name),
  CHECK (profile_key <> 'root'),
  CHECK (NOT can_update OR can_select)
);

CREATE INDEX IF NOT EXISTS user_branch_access_schema_user_idx
  ON public.user_branch_access (schema_name, user_id);

CREATE INDEX IF NOT EXISTS profile_table_permissions_schema_table_idx
  ON public.profile_table_permissions (schema_name, table_name, profile_key);

CREATE OR REPLACE FUNCTION private.is_root()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.user_access_profiles AS profile
    WHERE profile.user_id = (SELECT auth.uid())
      AND profile.profile_key = 'root'
  );
$$;

CREATE OR REPLACE FUNCTION private.current_profile_key()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT profile.profile_key
  FROM public.user_access_profiles AS profile
  WHERE profile.user_id = (SELECT auth.uid())
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION private.guard_root_profile()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF (TG_OP = 'INSERT' AND NEW.profile_key = 'root')
     OR (TG_OP = 'UPDATE' AND (OLD.profile_key = 'root' OR NEW.profile_key = 'root'))
     OR (TG_OP = 'DELETE' AND OLD.profile_key = 'root') THEN
    IF (SELECT auth.uid()) IS NOT NULL THEN
      RAISE EXCEPTION 'La cuenta root solo se puede crear o transferir mediante una operación administrativa.'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS guard_single_root_assignment
  ON public.user_access_profiles;
CREATE TRIGGER guard_single_root_assignment
  BEFORE INSERT OR UPDATE OR DELETE ON public.user_access_profiles
  FOR EACH ROW EXECUTE FUNCTION private.guard_root_profile();

-- Called manually from the SQL editor by a database administrator after the
-- chosen account has been created in Supabase Auth. It is not an API function.
CREATE OR REPLACE FUNCTION private.bootstrap_root(p_user_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF (SELECT auth.uid()) IS NOT NULL THEN
    RAISE EXCEPTION 'El alta inicial de root requiere una sesión administrativa de base de datos.'
      USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM auth.users AS auth_user WHERE auth_user.id = p_user_id) THEN
    RAISE EXCEPTION 'No existe ese usuario en Supabase Auth.' USING ERRCODE = '23503';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.user_access_profiles AS profile
    WHERE profile.profile_key = 'root'
  ) THEN
    RAISE EXCEPTION 'Ya existe una cuenta root.' USING ERRCODE = '23505';
  END IF;

  INSERT INTO public.user_access_profiles (user_id, profile_key)
  VALUES (p_user_id, 'root');
END;
$$;

-- Break-glass recovery is also SQL-editor only. The transaction keeps one root
-- assignment throughout; the old root becomes an unassigned admin.
CREATE OR REPLACE FUNCTION private.transfer_root(p_new_user_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_current_root uuid;
BEGIN
  IF (SELECT auth.uid()) IS NOT NULL THEN
    RAISE EXCEPTION 'La transferencia de root requiere una sesión administrativa de base de datos.'
      USING ERRCODE = '42501';
  END IF;

  SELECT profile.user_id
  INTO v_current_root
  FROM public.user_access_profiles AS profile
  WHERE profile.profile_key = 'root'
  FOR UPDATE;

  IF v_current_root IS NULL THEN
    RAISE EXCEPTION 'No existe una cuenta root para transferir.' USING ERRCODE = '23505';
  END IF;
  IF v_current_root = p_new_user_id THEN
    RETURN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM auth.users AS auth_user WHERE auth_user.id = p_new_user_id) THEN
    RAISE EXCEPTION 'No existe ese usuario en Supabase Auth.' USING ERRCODE = '23503';
  END IF;

  UPDATE public.user_access_profiles
  SET profile_key = 'admin', updated_at = now()
  WHERE user_id = v_current_root;

  INSERT INTO public.user_access_profiles (user_id, profile_key)
  VALUES (p_new_user_id, 'root')
  ON CONFLICT (user_id) DO UPDATE
    SET profile_key = 'root', updated_at = now();
END;
$$;

CREATE OR REPLACE FUNCTION public.root_list_users()
RETURNS TABLE (
  user_id uuid,
  email text,
  created_at timestamptz,
  profile_key text,
  branch_schemas text[]
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT private.is_root() THEN
    RAISE EXCEPTION 'Solo root puede consultar usuarios y perfiles.' USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  SELECT
    auth_user.id,
    auth_user.email::text,
    auth_user.created_at,
    profile.profile_key,
    COALESCE(
      array_agg(branch.schema_name::text ORDER BY branch.schema_name)
        FILTER (WHERE branch.schema_name IS NOT NULL),
      ARRAY[]::text[]
    )
  FROM auth.users AS auth_user
  LEFT JOIN public.user_access_profiles AS profile
    ON profile.user_id = auth_user.id
  LEFT JOIN public.user_branch_access AS branch
    ON branch.user_id = auth_user.id
  GROUP BY auth_user.id, auth_user.email, auth_user.created_at, profile.profile_key
  ORDER BY auth_user.email NULLS LAST, auth_user.id;
END;
$$;

CREATE OR REPLACE FUNCTION public.root_list_profile_matrix(
  p_profile_key text,
  p_schema_name text
)
RETURNS TABLE (
  table_name text,
  can_select boolean,
  can_insert boolean,
  can_update boolean,
  can_delete boolean
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT private.is_root() THEN
    RAISE EXCEPTION 'Solo root puede consultar la matriz de permisos.' USING ERRCODE = '42501';
  END IF;
  IF p_profile_key NOT IN ('admin', 'gerencia', 'almacen') THEN
    RAISE EXCEPTION 'Perfil no editable.' USING ERRCODE = '22023';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.empresas_esquemas AS branch
    WHERE branch.schema_name = p_schema_name
  ) THEN
    RAISE EXCEPTION 'Sucursal no registrada.' USING ERRCODE = '22023';
  END IF;

  RETURN QUERY
  SELECT
    relation.relname::text,
    COALESCE(permission.can_select, false),
    COALESCE(permission.can_insert, false),
    COALESCE(permission.can_update, false),
    COALESCE(permission.can_delete, false)
  FROM pg_catalog.pg_class AS relation
  JOIN pg_catalog.pg_namespace AS namespace
    ON namespace.oid = relation.relnamespace
  LEFT JOIN public.profile_table_permissions AS permission
    ON permission.profile_key = p_profile_key
   AND permission.schema_name = p_schema_name
   AND permission.table_name = relation.relname::text
  WHERE namespace.nspname = p_schema_name
    AND relation.relkind IN ('r', 'p')
  ORDER BY relation.relname;
END;
$$;

CREATE OR REPLACE FUNCTION public.root_set_user_profile(
  p_user_id uuid,
  p_profile_key text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT private.is_root() THEN
    RAISE EXCEPTION 'Solo root puede asignar perfiles.' USING ERRCODE = '42501';
  END IF;
  IF p_profile_key NOT IN ('admin', 'gerencia', 'almacen') THEN
    RAISE EXCEPTION 'El perfil debe ser admin, gerencia o almacen.' USING ERRCODE = '22023';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM auth.users AS auth_user WHERE auth_user.id = p_user_id) THEN
    RAISE EXCEPTION 'No existe ese usuario en Supabase Auth.' USING ERRCODE = '23503';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.user_access_profiles AS profile
    WHERE profile.user_id = p_user_id AND profile.profile_key = 'root'
