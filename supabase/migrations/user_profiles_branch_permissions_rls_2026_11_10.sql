$$;

CREATE OR REPLACE FUNCTION public.root_remove_user_access(p_user_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT private.is_root() THEN
    RAISE EXCEPTION 'Solo root puede revocar accesos.' USING ERRCODE = '42501';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.user_access_profiles AS profile
