CREATE OR REPLACE FUNCTION public.root_set_user_branches(
  p_user_id uuid,
  p_schema_names text[]
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_profile_key text;
  v_schema_names text[] := COALESCE(p_schema_names, ARRAY[]::text[]);
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT private.is_root() THEN
    RAISE EXCEPTION 'Solo root puede asignar sucursales.' USING ERRCODE = '42501';
  END IF;

  SELECT profile.profile_key INTO v_profile_key
  FROM public.user_access_profiles AS profile
  WHERE profile.user_id = p_user_id;
  IF v_profile_key IS NULL THEN
    RAISE EXCEPTION 'Asigna un perfil al usuario antes de asignarle sucursales.' USING ERRCODE = '23503';
  END IF;
  IF v_profile_key = 'root' THEN
    RAISE EXCEPTION 'Root tiene acceso global y no requiere asignaciones de sucursal.' USING ERRCODE = '42501';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM unnest(v_schema_names) AS requested(schema_name)
    LEFT JOIN public.empresas_esquemas AS branch
      ON branch.schema_name = requested.schema_name
    WHERE branch.schema_name IS NULL
  ) THEN
    RAISE EXCEPTION 'Todas las sucursales deben existir en empresas_esquemas.' USING ERRCODE = '22023';
  END IF;

  DELETE FROM public.user_branch_access AS access
  WHERE access.user_id = p_user_id;

  INSERT INTO public.user_branch_access (user_id, schema_name)
  SELECT p_user_id, requested.schema_name
  FROM (SELECT DISTINCT schema_name FROM unnest(v_schema_names) AS input(schema_name)) AS requested;
END;
$$;

CREATE OR REPLACE FUNCTION public.root_save_profile_matrix(
  p_profile_key text,
  p_schema_name text,
  p_permissions jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_table_count integer;
  v_input_count integer;
  v_distinct_count integer;
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT private.is_root() THEN
    RAISE EXCEPTION 'Solo root puede modificar permisos.' USING ERRCODE = '42501';
  END IF;
  IF p_profile_key NOT IN ('admin', 'gerencia', 'almacen') THEN
    RAISE EXCEPTION 'Perfil no editable.' USING ERRCODE = '22023';
  END IF;
  IF jsonb_typeof(p_permissions) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'La matriz debe ser un arreglo JSON.' USING ERRCODE = '22023';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.empresas_esquemas AS branch
    WHERE branch.schema_name = p_schema_name
  ) OR pg_catalog.to_regnamespace(p_schema_name) IS NULL THEN
    RAISE EXCEPTION 'Sucursal no registrada o esquema inexistente.' USING ERRCODE = '22023';
  END IF;

  SELECT count(*) INTO v_table_count
  FROM pg_catalog.pg_class AS relation
  JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = relation.relnamespace
  WHERE namespace.nspname = p_schema_name AND relation.relkind IN ('r', 'p');

  SELECT count(*), count(DISTINCT input.table_name)
  INTO v_input_count, v_distinct_count
  FROM pg_catalog.jsonb_to_recordset(p_permissions) AS input(
    table_name text,
    can_select boolean,
    can_insert boolean,
    can_update boolean,
    can_delete boolean
  );
  IF v_input_count <> v_table_count OR v_distinct_count <> v_table_count THEN
    RAISE EXCEPTION 'La matriz debe incluir cada tabla del esquema una sola vez.' USING ERRCODE = '22023';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM pg_catalog.jsonb_to_recordset(p_permissions) AS input(
      table_name text,
      can_select boolean,
      can_insert boolean,
      can_update boolean,
      can_delete boolean
    )
    LEFT JOIN pg_catalog.pg_class AS relation
      ON relation.relname = input.table_name
     AND relation.relkind IN ('r', 'p')
    LEFT JOIN pg_catalog.pg_namespace AS namespace
      ON namespace.oid = relation.relnamespace
     AND namespace.nspname = p_schema_name
    WHERE input.table_name IS NULL
       OR input.can_select IS NULL
       OR input.can_insert IS NULL
       OR input.can_update IS NULL
       OR input.can_delete IS NULL
       OR namespace.oid IS NULL
       OR (input.can_update AND NOT input.can_select)
  ) THEN
    RAISE EXCEPTION 'La matriz contiene datos inválidos o UPDATE sin SELECT.' USING ERRCODE = '22023';
  END IF;

  DELETE FROM public.profile_table_permissions AS permission
  WHERE permission.profile_key = p_profile_key
    AND permission.schema_name = p_schema_name;

  INSERT INTO public.profile_table_permissions (
    profile_key, schema_name, table_name,
    can_select, can_insert, can_update, can_delete
  )
  SELECT
    p_profile_key,
    p_schema_name,
    input.table_name,
    input.can_select,
    input.can_insert,
    input.can_update,
    input.can_delete
  FROM pg_catalog.jsonb_to_recordset(p_permissions) AS input(
    table_name text,
    can_select boolean,
    can_insert boolean,
    can_update boolean,
    can_delete boolean
  );
END;
$$;

